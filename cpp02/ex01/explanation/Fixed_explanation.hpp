#ifndef FIXED_HPP // ヘッダーガードの開始
#define FIXED_HPP // これにより、同じヘッダーファイルが複数回インクルードされるのを防ぎます。
                  // コンパイルエラーや重複定義の問題を避けるために重要です。

#include <string>   // 今回のFixedクラスでは直接使用していませんが、文字列操作が必要な場合に含めます。
                    // 今回の課題要件上は不要ですが、含めても問題ありません。
#include <iostream> // 標準入出力ストリーム (std::cout, std::endlなど) を使うために必要です。
#include <cmath>    // roundf関数を使うために必要です。Fixed::Fixed(const float)コンストラクタで使います。
                    // Fixed.cppだけでなく、Fixed.hppにも含めることで、
                    // Fixedクラスを使う他のファイルがcmathの関数を認識できるようになります。

// Fixed クラスの宣言
// このクラスは、固定小数点数を表現するためのものです。
// 整数と浮動小数点数の両方を内部で同じ固定小数点形式で扱えるように設計されています。
class Fixed
{
    // private (プライベート) メンバー:
    // これらのメンバーには、クラスの外部から直接アクセスできません。
    // カプセル化 (情報隠蔽) の原則により、クラスの内部実装を保護し、
    // 誤った使い方を防ぎ、変更に強くします。
    private:
        int value; // 固定小数点数を表す実際の値。これは整数型で格納されます。
                   // 小数点以下の部分は、後述する fractionalBits の数だけビットシフトして表現されます。

        // static const int fractionalBits = 8;
        // `static`: このメンバー変数は、Fixedクラスのすべてのインスタンスで共有される唯一のコピーです。
        //            Fixedオブジェクトを何個作っても、この `fractionalBits` は1つしか存在しません。
        // `const`: この値は一度設定されたら変更できません。定数です。
        // `int`: 整数型。
        // `8`: 小数点以下の桁数を8ビットで表現することを示します。
        //      例えば、`1.0` は内部的には `1 * (2^8)` = `256` として格納されます。
        static const int fractionalBits = 8; // C++98では、この初期化はクラス内で行うことが推奨されます。

    // public (パブリック) メンバー:
    // これらのメンバーには、クラスの外部から自由にアクセスできます。
    // クラスの「インターフェース」として機能し、Fixedオブジェクトを操作するための方法を提供します。
    public:
        // コンストラクタ群 (オブジェクトが生成されるときに呼び出される特殊な関数)
        Fixed();                  // 1. デフォルトコンストラクタ: 引数なしでオブジェクトを初期化します。(例: Fixed a;)
        ~Fixed();                 // 2. デストラクタ: オブジェクトが破棄されるときに呼び出されます。(メモリ解放など)
        Fixed(const Fixed& copy); // 3. コピーコンストラクタ: 既存のFixedオブジェクトから新しいオブジェクトを初期化します。(例: Fixed d(b);)
        Fixed(const int value);   // 4. int型引数を受け取るコンストラクタ: 整数からFixedオブジェクトを初期化します。(例: Fixed b(10);)
        Fixed(const float value); // 5. float型引数を受け取るコンストラクタ: 浮動小数点数からFixedオブジェクトを初期化します。(例: Fixed c(42.42f);)

        // 代入演算子オーバーロード (既存のオブジェクトに別のオブジェクトを代入するとき)
        // 例: a = Fixed(1234.4321f);
        Fixed &operator=(const Fixed &src); // `&` は参照を意味し、オブジェクトのコピーではなく直接操作します。
                                            // `const` は、代入元オブジェクト (src) が変更されないことを保証します。
                                            // 戻り値の `Fixed &` は連結代入 (a = b = c) を可能にします。

        // メンバー関数群 (Fixedオブジェクトが持つ操作や機能)
        int getRawBits(void) const;   // 内部の生の固定小数点値 (整数) を取得します。`const` はオブジェクトの状態を変更しないことを示します。
        void setRawBits(int const raw); // 内部の生の固定小数点値 (整数) を設定します。

        float toFloat(void) const;    // 固定小数点値を浮動小数点数に変換して返します。`const` です。
        int toInt(void) const;        // 固定小数点値を整数に変換して返します (小数点以下は切り捨て)。`const` です。
};

// 挿入演算子 `<<` のオーバーロード (グローバル関数)
// この関数はFixedクラスの「メンバー」ではありませんが、Fixedオブジェクトを `std::cout` などで
// 出力できるようにするために必要です。
// `std::ostream& os`: 出力ストリーム (例: std::cout) への参照。
// `const Fixed& fixed`: 出力したいFixedオブジェクトへのconst参照。
// 戻り値の `std::ostream&` は、`std::cout << obj1 << obj2;` のような連結出力を可能にします。
std::ostream& operator<<(std::ostream& os, const Fixed& fixed);

#endif // ヘッダーガードの終わり
