#include "Fixed.hpp" // Fixedクラスの定義（宣言）が書かれたヘッダーファイルを読み込みます。
                     // これにより、main関数内でFixedクラスを使えるようになります。

int main( void ) // main関数: C++プログラムの実行はここから始まります。
{
    // Fixedクラスのオブジェクト（インスタンス）を作成し、初期化しています。
    // 各行で、どのコンストラクタが呼び出されるか、コメントで示します。

    Fixed a; // 1. デフォルトコンストラクタが呼び出されます。
             //    'a' は初期値 0.0 で初期化されます。

    Fixed const b( 10 ); // 2. int型引数を受け取るコンストラクタが呼び出されます。
                         //    'b' は整数値 10 を固定小数点数に変換して初期化されます。
                         //    'const' キーワードは、このオブジェクト 'b' が作成後に変更されないことを意味します。

    Fixed const c( 42.42f ); // 3. float型引数を受け取るコンストラクタが呼び出されます。
                             //    'c' は浮動小数点数 42.42f を固定小数点数に変換して初期化されます。
                             //    ここでも 'const' が付いているので、'c' は変更されません。

    Fixed const d( b ); // 4. コピーコンストラクタが呼び出されます。
                        //    既存のオブジェクト 'b' の内容を使って、新しいオブジェクト 'd' を初期化します。
                        //    'd' も 'const' なので変更されません。

    // 代入演算子のテスト
    // ここでは、まず一時的なFixedオブジェクトが作成され、その値が 'a' に代入されます。
    a = Fixed( 1234.4321f ); // まず、float型引数を受け取るコンストラクタが呼び出されて
                             // 一時的なFixedオブジェクトが作成されます。
                             // その後、その一時オブジェクトの内容が 'a' に**コピー代入**されます。
                             // 代入が完了すると、一時オブジェクトはすぐに破棄されます（デストラクタが呼ばれます）。

    // Fixedオブジェクトを浮動小数点数として出力するテスト
    // ここでは、Fixedクラスのためにオーバーロードした `operator<<` が呼び出されます。
    // `operator<<` の中で `toFloat()` 関数が呼び出され、値が浮動小数点数として表示されます。
    std::cout << "a is " << a << std::endl; // 'a' の値を浮動小数点数で出力
    std::cout << "b is " << b << std::endl; // 'b' の値を浮動小数点数で出力
    std::cout << "c is " << c << std::endl; // 'c' の値を浮動小数点数で出力
    std::cout << "d is " << d << std::endl; // 'd' の値を浮動小数点数で出力

    // Fixedオブジェクトを整数として出力するテスト
    // ここでは、Fixedクラスの `toInt()` メンバー関数が直接呼び出され、
    // 値が整数（小数点以下切り捨て）として表示されます。
    std::cout << "a is " << a.toInt() << " as integer" << std::endl; // 'a' の値を整数で出力
    std::cout << "b is " << b.toInt() << " as integer" << std::endl; // 'b' の値を整数で出力
    std::cout << "c is " << c.toInt() << " as integer" << std::endl; // 'c' の値を整数で出力
    std::cout << "d is " << d.toInt() << " as integer" << std::endl; // 'd' の値を整数で出力
    
    return 0; // プログラムが正常終了したことをオペレーティングシステムに伝えます。
              // ここでmain関数が終了すると、作成されたすべてのFixedオブジェクト (a, b, c, d) のデストラクタが、
              // 作成時とは逆の順序で自動的に呼び出されます。
}
