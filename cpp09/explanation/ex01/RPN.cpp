#include "RPN.hpp"

// --- コンストラクタ / デストラクタ / コピー関係 ---
RPN::RPN() {}
RPN::~RPN() {}

RPN::RPN(const RPN &other)
{
    *this = other;
}

RPN& RPN::operator=(const RPN &other)
{
    if(this != &other)
    {
        // stack も標準コンテナなので、そのまま代入（コピー）が可能です
        this->stack = other.stack;
    }
    return(*this);
}

// --- メインロジック：計算処理 ---
void RPN::calculate(const std::string &expression)
{
    std::stringstream ss(expression); // 文字列をスペース区切りで読み取るためのストリーム
    std::string token;

    // 前回の計算データが残っていたら空にする（安全策）
    while(!stack.empty()) stack.pop();
    
    // 文字列を1つずつ（トークンごとに）処理する
    while(ss >> token)
    {
        // A. 数字だった場合 (1文字かつ 0-9)
        if(token.length() == 1 && std::isdigit(token[0]))
        {
            // 文字の '3' を数値の 3 に変換してスタックに積む
            stack.push(token[0] - '0');
        }
        // B. 演算子 (+, -, *, /) だった場合
        else if(token.length() == 1 && std::string("+-*/").find(token) != std::string::npos)
        {
            // 計算には最低2つの数字が必要
            if(stack.size() < 2)
            {
                std::cerr << "Error" << std::endl;
                return;
            }

            // スタックの「上」から順に取り出す
            // 💡 重要: 先に取り出したほうが「右（b）」、次が「左（a）」になります
            int b = stack.top(); stack.pop();
            int a = stack.top(); stack.pop();

            // 演算子に応じた計算をして、結果をまたスタックに戻す
            if(token == "+")
                stack.push(a + b);
            else if(token == "-")
                stack.push(a - b);
            else if(token == "*")
                stack.push(a * b);
            else if(token == "/")
            {
                // ゼロ除算（0で割る）は数学的にNGなのでエラー
                if(b == 0)
                {
                    std::cerr << "Error" << std::endl;
                    return;
                }
                stack.push(a / b);
            }
        }
        // C. 数字でも演算子でもない変な文字が来た場合
        else
        {
            std::cerr << "Error" << std::endl;
            return;
        }
    }

    // --- 最終結果の確認 ---
    // 計算が終わったとき、スタックに「最後の一つ」だけが残っていればそれが答えです
    if(stack.size() == 1)
    {
        std::cout << stack.top() << std::endl;
    }
    else
    {
        // 数字が残りすぎている（例: "1 2 3 +"）などの場合はエラー
        std::cerr << "Error" << std::endl;
    }
}

/*
 * ==========================================================================
 * 【初学者向け：実装を成功させるためのテクニック集】
 * ==========================================================================
 *
 * 1. スタックからの取り出し順序（a と b の関係）
 * --------------------------------------------------------------------------
 * 引き算（-）や割り算（/）では、順番が逆になると答えが全く変わってしまいます。
 * スタックは「後に入れたものが先に出る」ため、以下のようになります。
 * [ 3 (a) ]  <- 先に積まれた（左側）
 * [ 4 (b) ]  <- 後に積まれた（右側）
 * ---------------------------
 * 1回目 pop() => 4 を取得 (b)
 * 2回目 pop() => 3 を取得 (a)
 * 計算 => a / b (3 / 4) の順で実行する！
 */



/*
 * 2. 'token[0] - '0'' の魔法（文字から数値への変換）
 * --------------------------------------------------------------------------
 * コンピュータは文字を「アスキーコード（番号）」で管理しています。
 * 文字の '0' は 48番、 '1' は 49番 ... と連続しています。
 * そのため、文字の '3' (51番) から '0' (48番) を引き算すると、
 * 51 - 48 = 3 となり、純粋な「数値の 3」を取り出すことができます。
 */

/*
 * 3. std::stringstream の便利さ
 * --------------------------------------------------------------------------
 * 入力文字列が "1   2  +" のようにスペースがバラバラでも、
 * ss >> token と書くだけで、空白を自動で読み飛ばして
 * "1"、"2"、"+" と一語ずつ正確に切り分けてくれます。
 * 面倒な「スペースの数え上げ」を自前でする必要がなくなります。
 */

/*
 * ==========================================================================
 * 【RPN計算の具体的ステップ：シミュレーション】
 * ==========================================================================
 * 例: 数式 "3 4 -" を計算する場合
 * --------------------------------------------------------------------------
 * 1. '3' を発見
 * -> stack.push(3) を実行
 * -> スタックの状態: [ 3 ]
 *
 * 2. '4' を発見
 * -> stack.push(4) を実行
 * -> スタックの状態: [ 3, 4 ] (上が4)
 *
 * 3. '-' を発見
 * - b = stack.top() (4) を取得して pop()
 * - a = stack.top() (3) を取得して pop()
 * - 計算実行: a - b => 3 - 4 = -1
 * - stack.push(-1) で結果を戻す
 * - スタックの状態: [ -1 ]
 *
 * 4. 全トークンの処理終了
 * - スタックに残った最後の一つ「-1」を出力して完了！
 * --------------------------------------------------------------------------
 */

 /*
 * ==========================================================================
 * 【補足：Error（計算失敗）と判定される重要なポイント】
 * ==========================================================================
 * プログラムが正常に結果を出せず "Error" と出力するのは、主に以下の2パターンです。
 *
 * 1. 計算途中で数字が足りなくなった場合（ステップ3のチェック）
 * --------------------------------------------------------------------------
 * 演算子（+, -, *, /）が現れたのに、スタックに数字が2個未満しか入っていない状態。
 * 例: "3 +" 
 * -> '3' を積む。次に '+' が来たが、計算相手がいない！
 * -> stack.size() < 2 の条件に該当し、"Error" を出力します。
 *
 * 2. 計算が終わったのに数字が余っている場合（ステップ4のチェック）
 * --------------------------------------------------------------------------
 * 数式を最後まで読み終わったのに、スタックに数字が2個以上残っている状態。
 * 例: "3 4 5 -"
 * -> '3', '4', '5' を積む。
 * -> '-' で '4' と '5' を使い、'4 - 5 = -1' を積む。
 * -> 全工程終了。しかしスタックには [ 3, -1 ] が残っている！
 * -> stack.size() == 1 ではないため、正しく計算が完了していないと判断し "Error" を出力します。
 * --------------------------------------------------------------------------
 */
