/*
 * RPN クラス
 * 逆ポーランド記法（例: "3 4 +"）を計算するためのクラスです。
 */
class RPN
{
    private:
        // --- 内部データ ---
        // std::stack は「本を積み重ねたような」データ構造です。
        // 一番最後に置いたもの(push)を、一番最初に取り出す(pop)のが特徴です。
        // RPNの計算には、この「一時的に数字を積んでおく」仕組みが必須です。
        std::stack<int> stack;

    public:
        // --- 基本セット（ orthodox canonical form ） ---
        RPN();                          // コンストラクタ
        ~RPN();                         // デストラクタ
        RPN(const RPN &other);          // コピーコンストラクタ
        RPN& operator=(const RPN &other); // 代入演算子

        // --- メインの動作 ---
        // 引数として受け取った数式（例: "1 2 + 3 *"）を解析し、
        // スタックを使って計算を行い、最終結果を表示します。
        void calculate(const std::string &expression);
};

#endif

