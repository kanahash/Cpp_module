/* ************************************************************************** */
/* main.cpp - RPNプログラムの実行入り口                                       */
/* ************************************************************************** */

#include "RPN.hpp"

int main(int ac, char **av)
{
    // --- 1. コマンドライン引数のチェック ---
    // プログラムを実行する際、正しい数の情報が渡されたかを確認します。
    // ac (Argument Count) は引数の数です。
    // [0]: プログラム名 (./RPN)
    // [1]: 計算したい式 ("3 4 +")
    // 合計で 2 つ必要です。
    if(ac != 2)
    {
        // 引数が 2 つでない（式がない、または多すぎる）場合は "Error" と出力。
        std::cerr << "Error" << std::endl;
        return(1); // 異常終了
    }

    // --- 2. RPN計算機のインスタンス化 ---
    // RPNクラスの「実体（オブジェクト）」を作成します。
    // これにより、RPN.cpp で定義した計算機能が使えるようになります。
    RPN rpn;

    // --- 3. 計算の実行 ---
    // ユーザーが入力した数式（av[1]）を calculate メソッドに渡します。
    // ここから先は RPN クラスがスタックを使って計算を行います。
    rpn.calculate(av[1]);

    return(0); // 正常終了
}

/*
 * ==========================================================================
 * 【初学者向け：main.cpp の役割まとめ】
 * ==========================================================================
 * 1. 受付 (ac != 2):
 * 「計算式を1つだけ持ってきましたか？」とはじき出します。
 *
 * 2. 道具の準備 (RPN rpn;):
 * スタックを内蔵した「RPN専用計算機」を1台用意します。
 *
 * 3. 実行依頼 (rpn.calculate(av[1]);):
 * 持ってきた式を計算機に投入します。あとは計算機の中身（RPN.cpp）が
 * 正しく答えを出すか、エラーを出すかしてくれます。
 * ==========================================================================
 */
