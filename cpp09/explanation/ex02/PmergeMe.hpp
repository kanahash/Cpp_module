/*
 * ==========================================================================
 * 【初学者向け：PmergeMe の設計意図とコンテナ選びのポイント】
 * ==========================================================================
 *
 * 1. なぜ std::vector と std::deque を選ぶのか？
 * --------------------------------------------------------------------------
 * この課題の目的は、アルゴリズムが同じでも「コンテナの構造」によって
 * 速度がどう変わるかを比較することにあります。
 *
 * ● std::vector:
 * メモリが一直線に並んでいるため、特定の場所をパッと見る（ランダムアクセス）
 * のが最強に速いです。ただし、間に要素を割り込ませる（挿入）ときは、
 * 後ろの要素を全員一歩ずつずらす必要があるため、少し時間がかかります。
 *
 * ● std::deque:
 * 複数のメモリブロックに分かれて管理されています。vector よりも「挿入」
 * に強い構造をしていますが、ランダムアクセスは vector よりわずかに複雑です。
 *
 * Ford-Johnson アルゴリズムの肝である「二分探索による挿入」において、
 * この両者の特性がどうタイムに影響するかを観察するのが狙いです。
 */



/*
 * 2. run 関数にまとめられたフロー
 * --------------------------------------------------------------------------
 * このクラスでは、外部（main.cpp）から run 関数をひとつ呼ぶだけで、
 * 「数値の読み込み」「パース」「ソート実行」「時間計測」「結果表示」
 * がすべて行われます。
 *
 * なぜ分けないのか？ -> 課題文に「データの管理部分も含めたすべての時間を
 * 計測すること」という指示があるため、一連の流れを一つの関数内で管理して
 * 正確にタイムを計れるように設計されています。
 */

/*
 * 3. ⚠️ 重要：コンテナ禁止ルールの再確認
 * --------------------------------------------------------------------------
 * 4. 2 の課題ルールには「前の課題で使ったコンテナは使えない」という制約があります。
 *
 * もし ex01 (RPN) で std::stack を使った場合、stack は内部でデフォルトで
 * std::deque を使用しています。
 * 厳しい評価者の場合、「deque はもう使ったよね？」と指摘される可能性があるため、
 * より安全に合格を目指すなら、deque の代わりに 【std::list】 を使用する
 * のが一般的です。
 * --------------------------------------------------------------------------
 */

 /*
 * ==========================================================================
 * 【補足：std::list を選択した場合の挙動とメリット】
 * ==========================================================================
 * もし deque の代わりに std::list を使用して実装する場合、
 * コンテナの性質の違いが「実行時間」としてより顕著（残酷）に現れます。
 *
 * ● std::list の弱点：イテレータの移動コスト
 * Ford-Johnson アルゴリズムでは、挿入位置を決めるために「二分探索」を行います。
 * vector のような配列型は、真ん中の要素を「インデックス」で一瞬で見れますが、
 * list は連結リスト構造なので、真ん中へ行くにも先頭からポインタを
 * 1つずつ手繰り寄せる（std::advance 等）必要があります。
 *
 * ● 評価ポイントとしての「圧倒的な差」
 * データ数が 3000個、10000個と増えるにつれ、list は vector よりも
 * 圧倒的に時間がかかるようになります。
 *
 * 評価者に対して、「list はメモリの挿入自体は速いものの、二分探索のための
 * シーク（移動）に膨大なコストがかかるため、結果としてこれだけの差が出た」
 * と理論的に説明できれば、非常に高い評価に繋がります。
 * --------------------------------------------------------------------------
 */
