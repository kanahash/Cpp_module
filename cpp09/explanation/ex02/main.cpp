#include "PmergeMe.hpp"

/**
 * main関数: プログラムが実行されたときに最初に動く場所
 * @param ac: 引数の個数 (Argument Count)
 * @param av: 引数の中身 (Argument Vector) - 文字列の配列
 */
int main(int ac, char **av)
{
    // --- STEP 1: 引数チェック ---
    // プログラム名自体が1つ目の引数(av[0])になるので、
    // 数字が入力されていれば ac は 2 以上になります。
    if(ac < 2)
    {
        // 引数がない場合はエラーメッセージを出して終了
        std::cerr << "Error: No arguments provided." << std::endl;
        return(1); // 異常終了（1を返すのが慣例）
    }

    // --- STEP 2: インスタンスの作成 ---
    // PmergeMeクラスを使えるように、実体（オブジェクト）を1つ作ります。
    PmergeMe solver;

    // --- STEP 3: ソート処理の実行 ---
    // solverの中にある run メソッドを呼び出します。
    // 引数の個数(ac)と、中身の配列(av)をそのまま渡します。
    // 実際の「数字のチェック」「ソート」「時間計測」はすべてこの中で行われます。
    solver.run(ac, av);

    // --- STEP 4: プログラムの終了 ---
    return(0); // 正常終了
}
