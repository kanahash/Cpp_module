/* ************************************************************************** */
/* main.cpp - プログラムの実行口（エントリーポイント）                        */
/* ************************************************************************** */

#include "BitcoinExchange.hpp"

int main(int ac, char **av)
{
    // --- 1. 引数チェック ---
    // ac (argument count) は引数の数です。
    // プログラム名(1) + 入力ファイル名(1) = 計2つ必要です。
    if(ac != 2)
    {
        // 引数が足りない、または多い場合は使い方を教えて終了します
        std::cerr << "Error: could not open file." << std::endl;
        return(1);
    }

    // --- 2. 安全装置（try-catch） ---
    // データベースファイルが見つからないなどの「予期せぬ重大エラー」が起きても
    // 画面がフリーズしたり強制終了したりしないように、ここで捕まえます。
    try
    {
        // BitcoinExchange のインスタンス（実体）を作成
        // このとき、コンストラクタが呼ばれて内部でデータベース(data.csv)を読み込みます。
        BitcoinExchange btc(DB_FILE_NAME);

        // ユーザーが指定したファイル（av[1]）を使って、換算処理を開始します。
        btc.execute(av[1]);
    }
    catch(const std::exception& e)
    {
        // 読み込み中などにエラーが発生した場合、ここへジャンプしてきます。
        // 何が原因だったのか（e.what()）を表示して安全に終了します。
        std::cerr << "Error: " << e.what() << std::endl;
        return(1);
    }

    return(0); // すべて正常に完了！
}

/*
 * ==========================================================================
 * 【初学者向け：この main.cpp のポイント】
 * ==========================================================================
 *
 * ● 引数 av[1] とは？
 * ターミナルで「./btc input.txt」と打ったときの「input.txt」の部分です。
 *
 * ● なぜ try-catch を使うのか？
 * 「data.csv が存在しない」といった致命的な問題は、プログラムの深い場所で
 * 発生します。それを main という一番高い場所でまとめてキャッチすることで、
 * どこでエラーが起きても最終的にここできれいに後始末ができるようになります。
 *
 * ● 役割の分担
 * main 自体は難しい計算をしません。「準備をして、実行して、見守る」だけ。
 * 実際の複雑な仕事はすべて BitcoinExchange クラスに任せています。
 */
