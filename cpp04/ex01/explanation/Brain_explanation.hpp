#ifndef BRAIN_HPP  // もし "BRAIN_HPP" がまだ定義されていなければ...
#define BRAIN_HPP  // "BRAIN_HPP" を定義します。
                   // これは、このヘッダーファイルが複数回インクルードされるのを防ぐための「インクルードガード」です。

#include <string>   // std::stringクラスを使うために、<string>ヘッダーをインクルードします。
#include <iostream> // 標準入出力ストリーム(std::coutなど)を使うために、<iostream>ヘッダーをインクルードします。

// Brainという名前のクラスを定義します。
class Brain
{
    private:
        // ideasは、Brainクラスの内部でのみアクセスできる「プライベート」なメンバー変数です。
        // std::string型の配列で、サイズは100です。
        // これには「アイデア」を文字列として格納することを想定しています。
        std::string ideas[100];

    public:
        // ここから下は、クラスの外からアクセスできる「パブリック」なメンバー関数です。

        // デフォルトコンストラクタ
        // 新しいBrainオブジェクトが作られるときに呼ばれます。
        Brain();

        // デストラクタ
        // Brainオブジェクトが破棄されるときに呼ばれます。
        ~Brain();

        // コピーコンストラクタ
        // 既存のBrainオブジェクトを元に、新しいBrainオブジェクトを作る際に呼ばれます。
        // `const Brain &copy` は、変更できない(const)別のBrainオブジェクトの参照(&)を受け取ります。
        Brain(const Brain &copy);

        // コピー代入演算子
        // 既存のBrainオブジェクトに、別のBrainオブジェクトを代入する際に呼ばれます。
        // `Brain &`は、オブジェクト自身への参照を返すことを意味します。
        Brain &operator=(const Brain &src);
};

#endif // #ifndefの終わり
