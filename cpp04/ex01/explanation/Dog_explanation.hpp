#ifndef DOG_HPP  // もし "DOG_HPP" がまだ定義されていなければ...
#define DOG_HPP  // "DOG_HPP" を定義します。
                   // これにより、このヘッダーファイルが複数回インクルードされるのを防ぎます。

#include "Animal.hpp" // 親クラスであるAnimalクラスの定義を読み込みます。
#include "Brain.hpp"  // Dogクラスが持つBrainクラスの定義を読み込みます。

// Dogというクラスを定義します。
// `: public Animal` は、DogクラスがAnimalクラスの機能や性質を引き継ぐ「子クラス」であることを示します。
// これを「継承」と呼びます。
class Dog : public Animal
{
    private:
        // `brain` は、Dogクラスの内部でのみアクセスできる「プライベート」なメンバー変数です。
        // Brainクラスのオブジェクトを指すポインタです。
        // これにより、DogはBrainを持つことができます。
        Brain* brain;

    public:
        // ここから下は、クラスの外からアクセスできる「パブリック」なメンバー関数です。

        // デフォルトコンストラクタ
        // 新しいDogオブジェクトが作られるときに呼ばれます。
        Dog();

        // デストラクタ
        // `virtual` キーワードは、継承関係においてデストラクタが正しく機能するために非常に重要です。
        // これにより、派生クラスのオブジェクトを基本クラスのポインタで削除しても、
        // 派生クラスのデストラクタが確実に呼び出されるようになります。
        virtual ~Dog();

        // コピーコンストラクタ
        // 既存のDogオブジェクトを元に、新しいDogオブジェクトを作る際に呼ばれます。
        // `const Dog &copy` は、変更できない(const)別のDogオブジェクトの参照(&)を受け取ります。
        Dog(const Dog &copy);

        // コピー代入演算子
        // 既存のDogオブジェクトに、別のDogオブジェクトを代入する際に呼ばれます。
        // `Dog &`は、オブジェクト自身への参照を返すことを意味します。
        Dog &operator=(const Dog &src);

    // `Animal`クラスの`makeSound`関数を、`Dog`クラス独自の処理で「上書き（オーバーライド）」します。
    // `virtual` は、この関数がポリモーフィズム（多態性）を持つことを示しています。
    // `const` は、この関数がオブジェクトの状態を変更しないことを保証します。
    virtual void makeSound() const;
    
    // `Brain`へのポインタを返す関数です。
    // `const` は、この関数がオブジェクトの状態を変更しないことを保証します。
    // `const Brain*` は、返されるポインタが指すBrainオブジェクトも変更できないことを示します。
    const Brain* getBrain() const;
};

#endif // #ifndefの終わり
