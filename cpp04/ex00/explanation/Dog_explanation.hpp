#ifndef DOG_HPP  // もし "DOG_HPP" がまだ定義されていなければ...
#define DOG_HPP  // "DOG_HPP" を定義する。
                 // これは「インクルードガード」というおまじないで、
                 // 同じヘッダーファイルが何度も読み込まれるのを防ぎ、コンパイルエラーを防ぎます。

#include "Animal.hpp" // "Animal.hpp"を読み込む。
                      // DogクラスはAnimalクラスの機能を使うので、その設計図が必要です。

class Dog : public Animal // ここから Dog クラスの定義が始まります。
                          // ": public Animal" は、DogクラスがAnimalクラスを「継承」することを意味します。
                          // これにより、DogクラスはAnimalクラスのメンバー変数や関数を自動的に引き継ぎます。
{
    private:              // 'private'は、このクラスの内部からしかアクセスできないことを示します。
                          // このコードでは、Dogクラス独自のメンバー変数はありません。

    public:               // 'public'は、どこからでもアクセスできることを示します。
                          // クラスの「外部向けインターフェース」を定義する場所です。
        Dog();            // デフォルトコンストラクタの宣言。
                          // Dogオブジェクトが作られるときに呼び出されます。

        virtual ~Dog();   // 仮想デストラクタの宣言。
                          // オブジェクトが破棄されるときに呼び出されます。
                          // 親クラスのAnimalでもvirtualになっているので、子クラスでもvirtualにしておくのが良い習慣です。

        Dog(const Dog &copy); // コピーコンストラクタの宣言。
                              // 既存のDogオブジェクトをコピーして新しいオブジェクトを作るときに呼び出されます。

        Dog &operator=(const Dog &src); // コピー代入演算子の宣言。
                                       // 既存のDogオブジェクトに別のDogオブジェクトを代入するときに呼び出されます。

    virtual void makeSound() const; // 'makeSound'関数の宣言。
                                    // 親クラス（Animal）にある同名の関数を「上書き」（オーバーライド）します。
                                    // virtualキーワードのおかげで、Animal*型やAnimal&型を使ってこの関数を呼び出した場合でも、
                                    // 実際のオブジェクトがDogであれば、Dog::makeSound()が呼び出されるようになります。
};

#endif // インクルードガードの終わり。
