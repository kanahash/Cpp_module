#ifndef ANIMAL_HPP  // もし "ANIMAL_HPP" がまだ定義されていなければ...
#define ANIMAL_HPP  // "ANIMAL_HPP" を定義する。
                    // これは「インクルードガード」と呼ばれ、同じヘッダーファイルが複数回読み込まれるのを防ぐおまじないです。
                    // これがないと、コンパイルエラーになることがあります。

#include<string>    // std::stringクラスを使うために、stringヘッダーファイルを読み込む。
#include<iostream>  // std::coutやstd::endlを使うために、iostreamヘッダーファイルを読み込む。

class Animal        // ここから Animal という名前のクラス（設計図）が始まります。
{
    protected:      // 'protected'は、このクラスと、このクラスを「継承」するクラスからのみアクセスできることを示します。
                    // 'private'よりも少し緩いアクセス権です。
        std::string type; // 動物の種類（例: "Dog", "Cat"）を保存するメンバー変数です。

    public:         // 'public'は、どこからでもアクセスできることを示します。
                    // クラスの「外部向けインターフェース」を定義する場所です。
        Animal();   // デフォルトコンストラクタの宣言。オブジェクトが作られるときに呼び出されます。

        virtual ~Animal(); // 仮想デストラクタの宣言。
                           // 'virtual'が付いているので、このクラスを継承したクラスのオブジェクトを削除する際に、
                           // 派生クラスのデストラクタが正しく呼び出されることを保証します。
                           // オブジェクト指向で継承を使う場合、デストラクタには'virtual'を付けるのが良い習慣です。

        Animal(const Animal &copy); // コピーコンストラクタの宣言。
                                    // 既存のオブジェクトをコピーして新しいオブジェクトを作るときに呼び出されます。

        Animal &operator=(const Animal &src); // コピー代入演算子の宣言。
                                             // 既存のオブジェクトに別のオブジェクトの値を代入するときに呼び出されます。

        std::string getType() const; // 'type'を取得する関数の宣言。
                                     // 最後に付いている 'const' は、この関数がオブジェクトの状態を変更しないことを示します。

        virtual void makeSound() const; // 'makeSound'関数の宣言。
                                        // 'virtual'が付いているので、このクラスを継承したクラス（例：DogやCat）で
                                        // この関数を上書き（オーバーライド）することができます。
                                        // ポインタや参照を介して呼び出された場合でも、
                                        // 実際のオブジェクトの型に応じた関数が呼び出されます。
};

#endif // インクルードガードの終わり。
