#ifndef CAT_HPP  // もし "CAT_HPP" がまだ定義されていなければ...
#define CAT_HPP  // "CAT_HPP" を定義する。
                 // これは「インクルードガード」というおまじないで、
                 // 同じヘッダーファイルが何度も読み込まれるのを防ぎ、コンパイルエラーを防ぎます。

#include "Animal.hpp" // "Animal.hpp"を読み込む。
                      // CatクラスはAnimalクラスの機能を使うので、その設計図が必要です。

class Cat : public Animal // ここから Cat クラスの定義が始まります。
                          // ": public Animal" は、CatクラスがAnimalクラスを「継承」することを意味します。
                          // これにより、CatクラスはAnimalクラスのメンバー変数や関数を自動的に引き継ぎます。
{
    private:              // 'private'は、このクラスの内部からしかアクセスできないことを示します。
                          // このコードでは、Catクラス独自のメンバー変数はありません。

    public:               // 'public'は、どこからでもアクセスできることを示します。
                          // クラスの「外部向けインターフェース」を定義する場所です。
        Cat();            // デフォルトコンストラクタの宣言。
                          // Catオブジェクトが作られるときに呼び出されます。

        virtual ~Cat();   // 仮想デストラクタの宣言。
                          // オブジェクトが破棄されるときに呼び出されます。
                          // 親クラスのAnimalでもvirtualになっているので、子クラスでもvirtualにしておきます。

        Cat(const Cat &copy); // コピーコンストラクタの宣言。
                              // 既存のCatオブジェクトをコピーして新しいオブジェクトを作るときに呼び出されます。

        Cat &operator=(const Cat &src); // コピー代入演算子の宣言。
                                       // 既存のCatオブジェクトに別のCatオブジェクトを代入するときに呼び出されます。

    virtual void makeSound() const; // 'makeSound'関数の宣言。
                                    // 親クラス（Animal）にある同名の関数を「上書き」（オーバーライド）します。
                                    // virtualキーワードのおかげで、Animal*型やAnimal&型を使ってこの関数を呼び出した場合でも、
                                    // 実際のオブジェクトがCatであれば、Cat::makeSound()が呼び出されるようになります。
};

#endif // インクルードガードの終わり。
