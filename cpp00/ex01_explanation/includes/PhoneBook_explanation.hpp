// インクルードガード（Include Guard）と呼ばれるものです。
// これにより、このヘッダーファイルが複数回含まれることによるエラーを防ぎます。
// 例えば、他のファイルがこのPhoneBook.hppを2回インクルードしようとしても、
// 1回目ですでに定義されているため、2回目以降は無視されます。
#ifndef PHONEBOOK_HPP // もしPHONEBOOK_HPPがまだ定義されていなければ
#define PHONEBOOK_HPP // PHONEBOOK_HPPを定義する

// 必要なヘッダーファイルを読み込みます。
// "Contact.hpp"は、PhoneBookクラスがContactクラスのオブジェクトを使用するため、必須です。
#include "Contact.hpp"
// <string>は、文字列を扱うためのstd::stringクラスを使用するために必要です。
#include <string>
// <iomanip>は、出力のフォーマット（例えば、表示幅の調整など）を制御するために必要です。
// std::setwなどの関数が含まれています。
#include <iomanip>
// <sstream>は、文字列ストリーム（文字列の読み書きをストリームとして扱う）を
// 使用するために必要ですが、このヘッダーファイルでは直接使われていません。
// おそらく実装ファイル（.cpp）で使われる予定か、過去に使われていた可能性があります。
#include <sstream>

// PhoneBookクラスの定義を開始します。
// このクラスは電話帳の機能（連絡先の追加、検索など）を管理します。
class PhoneBook
{
	// private: の下に宣言されたメンバー（変数や関数）は、
	// そのクラスの内部からのみアクセスできます。
	// クラスの外からは直接アクセスできません。
	private:
		// 現在の連絡先を追加する位置を示すインデックスです。
		// 新しい連絡先が追加されるたびに更新されます。
		int index;
		// 8つのContactオブジェクトを格納できる配列です。
		// これが電話帳に保存される連絡先の実体となります。
		// 配列のサイズが8に固定されているため、電話帳は最大8件の連絡先を保存できます。
		Contact contact_lists[8];
		// 現在電話帳に保存されている連絡先の実際の数です。
		// indexとは異なり、追加された連絡先の総数を正確に追跡します。
		int num_contacts;
		// 連絡先の一覧を表示するためのプライベート関数です。
		// 検索機能の一部として使われることが想定されます。
		void printContactlist();
		// indexをインクリメント（1増やす）し、必要に応じて0に戻すためのプライベート関数です。
		// 例えば、8件を超えたら最初の位置に戻る（古い連絡先を上書きする）ロジックが
		// 含まれる可能性があります。
		void incrementIndex();
		// 指定されたインデックスの連絡先の詳細を表示するためのプライベート関数です。
		void printContact(int index);
		// ユーザーから有効な連絡先インデックス（番号）を取得するためのプライベート関数です。
		// ユーザーの入力が数値であるか、有効な範囲内であるかを検証します。
		// 取得に成功したらtrue、失敗したらfalseを返します。
		bool getIndexFromUser(int& selected_index);
		// ユーザーから連絡先の詳細情報を取得するためのプライベート関数です。
		// 入力された情報をContactオブジェクトに設定します。
		// 全ての詳細が正しく取得できたらtrue、途中でエラーや中断があったらfalseを返します。
		bool getContactDetails(Contact& contact);

	// public: の下に宣言されたメンバーは、クラスの外からでもアクセスできます。
	// これらの関数が、PhoneBookクラスの「インターフェース」（外部から使える機能）となります。
	public:
	// PhoneBookクラスのコンストラクタです。
	// PhoneBookオブジェクトが作成されるときに自動的に呼び出され、
	// メンバー変数の初期化などを行います。
	PhoneBook();
	// PhoneBookクラスのデストラクタです。
	// PhoneBookオブジェクトが破棄されるときに自動的に呼び出され、
	// 割り当てられたリソースの解放などを行います。
	// このクラスでは明示的なメモリ割り当てがないため、通常は空の実装になります。
	~PhoneBook();

	// 新しい連絡先を電話帳に追加するためのパブリック関数です。
	// 連絡先の追加が成功したらtrue、失敗したらfalseを返します。
	bool addContact();
	// 電話帳から連絡先を検索し、表示するためのパブリック関数です。
	// 検索処理が成功したらtrue、失敗したらfalseを返します。
	bool searchContact();
};

#endif // PHONEBOOK_HPPの終わり
