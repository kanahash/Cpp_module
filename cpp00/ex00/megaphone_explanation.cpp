// 必要なヘッダーファイルを読み込みます。
// iostreamは、標準入出力（画面への表示など）を行うために必要です。
#include<iostream>
// stringは、文字列を扱うために必要ですが、このコードではC形式の文字列（char配列）を
// 主に使っているので、必須ではありませんが、あっても問題ありません。
#include<string>
// cctypeヘッダーは、toupper関数（文字を大文字に変換する関数）を使うために必要ですが、
// このコードには明示的に記述されていません。しかし、多くのコンパイラでは
// iostreamなどの他のヘッダーを通じて間接的に含まれることがあります。
// 正確には #include<cctype> を追加するべきです。

// プログラムの開始点となるmain関数です。
// int ac: 引数の数（Argument Count）を表します。プログラム名自身も1つと数えられます。
// char **av: 引数の値（Argument Vector）を表します。文字列の配列として渡されます。
// av[0]はプログラム名、av[1]以降がユーザーが入力した引数になります。
int main(int ac, char **av)
{
	// もし引数の数が1つだけ（つまり、プログラム名しか入力されなかった場合）
	if(ac == 1)
		// 「* LOUD AND UNBEARABLE FEEDBACK NOISE *」というメッセージを表示します。
		// std::cout は画面に文字を出力するためのものです。
		// std::endl は改行を行い、出力バッファをフラッシュします。
		std::cout << "* LOUD AND UNBEARABLE FEEDBACK NOISE *" << std::endl;
	// 引数が1つ以上ある場合（つまり、ユーザーが何か文字列を入力した場合）
	else
	{
		// i は、引数の配列 av をループするためのカウンターです。
		// 最初の引数 av[0] はプログラム名なので、ユーザーが入力した引数は av[1] から始まります。
		int i = 1;
		// j は、各引数の文字列内の文字をループするためのカウンターです。
		int j;
		// 引数がなくなるまでループを続けます。
		// i は av のインデックス（添字）で、ac は引数の総数です。
		// i が ac より小さい間（つまり、まだ処理すべき引数がある間）ループします。
		while(i < ac)
		{
			// 各引数の文字列の先頭から文字を処理するために、j を0にリセットします。
			j = 0;
			// 現在の引数 av[i] の文字列内の文字がなくなるまでループを続けます。
			// C言語スタイルの文字列は、最後にヌル文字（'\0'）が入っているので、
			// av[i][j] がヌル文字でない間は文字があると判断できます。
			while(av[i][j])
			{
				// std::toupper関数を使って、現在の文字 av[i][j] を大文字に変換し、
				// その結果を元の場所 av[i][j] に上書きします。
				av[i][j] = std::toupper(av[i][j]);
				// 次の文字に進むために j をインクリメント（1増やす）します。
				j++;
			}
			// 現在処理している引数（文字列全体が大文字に変換されている）を表示します。
			std::cout <<av[i];
			// 次の引数に進むために i をインクリメントします。
			i++;
		}
		// すべての引数を表示し終わった後、最後に改行します。
		std::cout<<std::endl;
	}
	// プログラムが正常に終了したことをOSに伝えます。
	return(0);
}
